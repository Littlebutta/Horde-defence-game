def dark(c, f):
    return tuple(int(v * f) for v in c)

# (sprite, background, body, shade, eyes)
CELLS = [
    (ZOMBIE, dark((20, 120, 40), 0.75), (92, 220, 110), (10, 60, 20), (255, 70, 60)),
    (BUG, dark((120, 30, 170), 0.75), (222, 120, 255), (90, 20, 130), (255, 240, 120)),
    (ORC, dark((170, 50, 0), 0.75), (255, 140, 50), (110, 30, 0), (255, 230, 80)),
    (CIV, (44, 50, 60), (255, 255, 255), (30, 34, 40), (30, 34, 40)),
]
TUSK = (250, 244, 225)
GAP = (16, 18, 22)

def master():
    img = Image.new("RGBA", (32, 32))
    for i, (spr, bg, body, shade, eye) in enumerate(CELLS):
        ox, oy = (i % 2) * 16, (i // 2) * 16
        for y, row in enumerate(spr.strip().splitlines()):
            for x, ch in enumerate(row):
                c = {".": bg, "#": body, "o": shade, "x": eye, "w": TUSK}[ch]
                img.putpixel((ox + x, oy + y), c + (255,))
    return img

def render(size):
    m = master()
    if size < 32:
        # too small for the units: plain squares in the army colours
        img = Image.new("RGBA", (size, size), GAP + (255,))
        h = size // 2
        for i, (_, _, body, _, _) in enumerate(CELLS):
            ox, oy = (i % 2) * h, (i // 2) * h
            for y in range(h):
                for x in range(h):
                    img.putpixel((ox + x, oy + y), body + (255,))
        return img
    s = (size + 31) // 32
    img = m.resize((32 * s, 32 * s), Image.NEAREST)
    if img.size[0] != size:
        img = img.resize((size, size), Image.LANCZOS)
    # dark cross between the four squares
    w = max(1, size // 64)
    for y in range(size):
        for x in range(size // 2 - w, size // 2 + w):
            img.putpixel((x, y), GAP + (255,))
            img.putpixel((y, x), GAP + (255,))
    # dark frame
    for k in range(w):
        for t in range(size):
            for p in ((t, k), (t, size - 1 - k), (k, t), (size - 1 - k, t)):
                img.putpixel(p, GAP + (255,))
    return img

out = Path(__file__).resolve().parent.parent / "assets"
big = render(256)
big.save(out / "icon.png")
sizes = [16, 24, 32, 48, 64, 128, 256]
imgs = [render(s) for s in sizes]
imgs[-1].save(out / "icon.ico", format="ICO", sizes=[(s, s) for s in sizes], append_images=imgs[:-1])
for s in (16, 32, 64):
    (out / f"icon{s}.rgba").write_bytes(render(s).tobytes())
